  function tr(lang, key, params) {
    var activeLang = STRINGS[lang] ? lang : "en";
    var tpl = STRINGS[activeLang][key];
    if (tpl === undefined) {
      tpl = STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
    }
    if (!params) return tpl;
    return tpl.replace(/\{([a-zA-Z0-9_]+)\}/g, function (_, k) {
      return params[k] !== undefined && params[k] !== null ? String(params[k]) : "";
    });
  }

  function formatHourLabel(hour24, lang) {
    var h12 = hour24 <= 12 ? hour24 : hour24 - 12;
    var isAm = hour24 < 12;
    if (lang === "hi") {
      return h12 + (isAm ? " सु" : " शा");
    }
    if (lang === "kn") {
      return h12 + (isAm ? " ಬೆ" : " ಸಂ");
    }
    return h12 + (isAm ? "AM" : "PM");
  }

  function localizeCategory(cat, lang) {
    var key = CATEGORY_KEY_MAP[cat];
    return key ? tr(lang, key) : cat;
  }

  function localizeAuditRow(row, lang) {
    if (lang === "en") {
      return {
        actor: row.actor,
        event: row.event_type,
        detail: row.detail
      };
    }
    var evMap = AUDIT_EVENT_LABELS[lang] || {};
    var evLabel = evMap[row.event_type] || row.event_type;
    var actorLow = String(row.actor || "").toLowerCase();
    var actMap = ACTOR_LABELS[lang] || {};
    var actorOut = actorLow.indexOf("voice") !== -1
      ? actMap.voice
      : (actorLow.indexOf("dashboard") !== -1 || actorLow.indexOf("cap") !== -1 || actorLow.indexOf("merchant") !== -1
          ? actMap.dashboard
          : evLabel);

    var nums = String(row.detail || "").match(/\d+(?:\.\d+)?/g) || [];
    var detailOut = evLabel;
    if (nums.length > 0) {
      var formattedNums = nums.slice(0, 4).map(function (x) { return fmtNum(x); }).join(" / ");
      detailOut = evLabel + " (" + formattedNums + ")";
    }
    return {
      actor: actorOut,
      event: evLabel,
      detail: detailOut
    };
  }

